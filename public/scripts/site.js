const fallbackLanguage = "en";
const supportedLanguages = ["en", "de", "fr", "es", "it", "nl", "pt"];
const languageSelect = document.querySelector("[data-language-select]");
const themeToggle = document.querySelector("[data-theme-toggle]");
const themeIcon = document.querySelector("[data-theme-icon]");

function normalizeLanguage(language) {
  return supportedLanguages.includes(language) ? language : fallbackLanguage;
}

function getDictionary(language) {
  return { ...translations.en, ...(translations[normalizeLanguage(language)] || {}) };
}

function updateThemeLabel(dictionary = getDictionary(localStorage.getItem("language") || fallbackLanguage)) {
  const label = themeToggle?.querySelector("[data-i18n='themeToggle']");
  const isDark = document.documentElement.classList.contains("dark");
  if (label) label.textContent = isDark ? dictionary.themeToggleLight : dictionary.themeToggle;
  if (themeIcon) themeIcon.textContent = isDark ? "Sun" : "Moon";
}

function applyLanguage(language) {
  const normalizedLanguage = normalizeLanguage(language);
  const dictionary = getDictionary(normalizedLanguage);
  document.documentElement.lang = normalizedLanguage;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (key && dictionary[key]) element.textContent = dictionary[key];
  });
  if (languageSelect) languageSelect.value = normalizedLanguage;
  localStorage.setItem("language", normalizedLanguage);
  updateThemeLabel(dictionary);
}

function applyTheme(theme) {
  document.documentElement.classList.toggle("dark", theme === "dark");
  localStorage.setItem("theme", theme);
  updateThemeLabel();
}

applyLanguage(localStorage.getItem("language") || fallbackLanguage);

languageSelect?.addEventListener("change", (event) => {
  applyLanguage(event.target.value);
});

themeToggle?.addEventListener("click", () => {
  const nextTheme = document.documentElement.classList.contains("dark") ? "light" : "dark";
  applyTheme(nextTheme);
});

